/**
 * @brief Run the complete LPDDR4 training sequence end-to-end.
 *
 * Convenience wrapper that, in order:
 *   1. Waits for PLL lock (::lpddr4_wait_pll_lock).
 *   2. Programs the training-enable bits (::lpddr4_start_training).
 *   3. Releases the IP from reset (::lpddr4_bring_out_of_reset).
 *   4. Polls the Status Register until training completes or any error
 *      bit asserts.
 *
 * The function selects the appropriate training-done mask based on the
 * configured number of ranks (#RANK0_TRN_DONE or #RANK1_TRN_DONE).
 *
 * @param[in] instance_ptr Driver instance handle.
 *
 * @retval NO_FAIL     Training completed successfully.
 * @retval CBT_FAIL    Command-Bus Training failed.
 * @retval WR_LVL_FAIL Write-leveling failed.
 * @retval RD_TRN_FAIL Read training failed.
 * @retval WR_TRN_FAIL Write training failed.
 * @retval OTHER_FAIL  @p instance_ptr is NULL or a sub-step failed.
 */
LPDDR_RET lpddr4_do_training(lpddr4 *instance_ptr)
{
    unsigned int ret;
    LPDDR_RET training_result = NO_FAIL;
    volatile int delay;
    status_reg_t sts_reg;
    feature_ctrl_reg_t fcr_reg;
    unsigned int trn_done_status;

    if (instance_ptr == IS_NULL)
    {
        return OTHER_FAIL;
    }

    /* Step 1: Wait for PLL lock */
    ret = lpddr4_wait_pll_lock(instance_ptr);
    if (ret != SUCCESS)
    {
        return OTHER_FAIL;
    }

    /* Step 2: Start training sequence */
    ret = lpddr4_start_training(instance_ptr);
    if (ret != SUCCESS)
    {
        return OTHER_FAIL;
    }

    /* Step 3: Bring LPDDR out of reset to start training sequence */
    ret = lpddr4_bring_out_of_reset(instance_ptr);
    if (ret != SUCCESS)
    {
        return OTHER_FAIL;
    }

    /* Determine training done status mask based on number of ranks */
    fcr_reg = lpddr4_GetFeatureControlReg(instance_ptr);
    trn_done_status = (fcr_reg.fields.num_ranks == 0) ? RANK0_TRN_DONE : RANK1_TRN_DONE;

    /* Step 4: Poll training status until complete or error */
    sts_reg = lpddr4_GetStatusReg(instance_ptr);
    while ((sts_reg.reg & trn_done_status) != trn_done_status)
    {
        sts_reg = lpddr4_GetStatusReg(instance_ptr);

        /* Check for errors immediately, regardless of phy_ready status */
        if (sts_reg.fields.cbt_err == 1)
        {
            return CBT_FAIL;
        }
        if (sts_reg.fields.write_lvl_err == 1)
        {
            return WR_LVL_FAIL;
        }
        if (sts_reg.fields.read_trn_err == 1)
        {
            return RD_TRN_FAIL;
        }
        if (sts_reg.fields.write_trn_err == 1)
        {
            return WR_TRN_FAIL;
        }

        /*Mandatory delay to sync with hardware training engine*/
        delay = TWO_US_DELAY;
        while (--delay)
        {
            __asm__ __volatile__("nop");
        }
    }
    return training_result;
}

