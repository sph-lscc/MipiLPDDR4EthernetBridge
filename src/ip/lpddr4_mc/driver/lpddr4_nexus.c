/**
 * @brief Block until the LPDDR4 PLL reports lock.
 *
 * Polls the Clock-Change Register until #PLL_LOCK_BIT is asserted.
 *
 * @param[in] instance_ptr Driver instance handle.
 *
 * @retval SUCCESS PLL is locked.
 * @retval FAILURE @p instance_ptr is NULL.
 *
 * @warning This function busy-waits indefinitely if the PLL never locks.
 */
unsigned int lpddr4_wait_pll_lock(lpddr4 *instance_ptr)
{
    if (instance_ptr == IS_NULL)
    {
        return FAILURE;
    }
    volatile clk_chng_t clk_chng_reg;

    /* Waiting until PLL is locked */
    do
    {
        clk_chng_reg = (clk_chng_t)lpddr4_read32(instance_ptr->lpddr4_base_address, CLK_CHANGE_REG);
    } while ((clk_chng_reg.reg & PLL_LOCK_BIT) != PLL_LOCK_BIT);

    return SUCCESS;
}

