/**
 * @brief : This API is used to set the MAC address of the Ethernet IP.
 * @param : this_xxv_xethernet - Handle of the xxv_xethernet_instance structure.
 *          mac_address - MAC address in char[6] format.
 *                        Example: if the MAC address is AC-DE-48-00-00-80,
 *                        Arrange it in char mac_address = {AC, DE, 48, 00, 00, 80};
 * @return : Return the success or failure status based on a condition.
 */
int xxv_xethernet_set_mac_address(xxv_xethernet_instance *this_xxv_xethernet, unsigned char *mac_address)
{
    if(!this_xxv_xethernet || !mac_address)
        return FAILURE;

    unsigned int mac_addr_lo = 0;
    mac_addr_lo = mac_address[0];
    mac_addr_lo |= (unsigned int) mac_address[1] << 8;
    mac_addr_lo |= (unsigned int) mac_address[2] << 16;
    mac_addr_lo |= (unsigned int) mac_address[3] << 24;

    unsigned int mac_addr_hi = 0;
    mac_addr_hi = (unsigned int) mac_address[4];
    mac_addr_hi |= (unsigned int) mac_address[5] << 8;

    register_write32(this_xxv_xethernet->config.base_address, MAC_ADDR_0, mac_addr_lo);
    register_write32(this_xxv_xethernet->config.base_address, MAC_ADDR_1, mac_addr_hi);

    return SUCCESS;
}

/**
 * @brief : This API is used to get the MAC address of the Ethernet IP.
 * @param : this_xxv_xethernet - Handle of the xxv_xethernet_instance structure.
 *          mac_address - MAC address in char[6] format.
 *                        Example: if the obtained mac_address = {AC, DE, 48, 00, 00, 80},
 *                                 it would be equivalent to AC-DE-48-00-00-80.
 * @return : Return the success or failure status based on a condition.
 */
int xxv_xethernet_get_mac_address(xxv_xethernet_instance *this_xxv_xethernet, char *mac_address)
{
    if(!this_xxv_xethernet || !mac_address)
        return FAILURE;

    unsigned int mac_addr_lo = register_read32(this_xxv_xethernet->config.base_address, MAC_ADDR_0);
    unsigned int mac_addr_hi = register_read32(this_xxv_xethernet->config.base_address, MAC_ADDR_1);

    mac_address[0] = (char) mac_addr_lo;
    mac_address[1] = (char) (mac_addr_lo >> 8);
    mac_address[2] = (char) (mac_addr_lo >> 16);
    mac_address[3] = (char) (mac_addr_lo >> 24);
    mac_address[4] = (char) mac_addr_hi;
    mac_address[5] = (char) (mac_addr_hi >> 8);

    return SUCCESS;
}

/**
 * @brief : This API is used to calculate CRC from MAC address.
 * @param : mac_address - MAC address in char[6] format.
 *          Example: if the MAC address is AC-DE-48-00-00-80,
 *                   Arrange it in char mac_address = {AC, DE, 48, 00, 00, 80};
 * @return : Return the computed CRC value.
 */
int xxv_xethernet_conv_mac_to_crc(char *mac_address)
{
    unsigned int crc = 0xFFFFFFFF;
    int carry = 0;
    int addr_index, bit_pos;
    for (addr_index = 0; addr_index < 6; ++addr_index)
    {
        for (bit_pos = 0; bit_pos < 8; ++bit_pos)
        {
            carry = (crc >> 31)^((mac_address[addr_index] & (1 << bit_pos)) >> bit_pos);
            crc <<= 1;
            if (carry){
                crc = (crc ^ CRC_POLYNOMIAL) | carry;
            }
        }
    }
    return crc;
}

/**
 * @brief : This API is used to set or clear multicast filter based on CRC value.
 * @param : this_xxv_xethernet - Handle of the xxv_xethernet_instance structure.
 *          crc - Represents the computed CRC value derived from the MAC address.
 * @return : Return the success or failure status based on a condition.
 */
int xxv_xethernet_multicast_bit_modify(xxv_xethernet_instance *this_xxv_xethernet, unsigned int crc, unsigned char isSet)
{
    if(!this_xxv_xethernet)
        return FAILURE;

    unsigned char table_num = ((crc >> 1) & 0x3F) >> 3;
    unsigned char bit_pos = ((crc >> 1) & 0x3F) & 0x07;

    unsigned int mc_table0_val = register_read32(this_xxv_xethernet->config.base_address, MC_TABLE_0);
    unsigned int mc_table1_val = register_read32(this_xxv_xethernet->config.base_address, MC_TABLE_1);
    unsigned long long mc_table_val = ((unsigned long long)mc_table1_val << 32) | (unsigned long long)mc_table0_val;
    unsigned char mc_table_array[sizeof(unsigned long long)];
    memcpy(mc_table_array, &mc_table_val, sizeof(unsigned long long));

    if (isSet)
    {
        mc_table_array[table_num] |= (1 << bit_pos);
    }
    else
    {
        mc_table_array[table_num] &= ~(1 << bit_pos);
    }

    memcpy(&mc_table_val, mc_table_array, sizeof(unsigned long long));
    mc_table0_val = (unsigned int) mc_table_val;
    mc_table1_val = (unsigned int) (mc_table_val >> 32);

    register_write32(this_xxv_xethernet->config.base_address, MC_TABLE_0, mc_table0_val);
    register_write32(this_xxv_xethernet->config.base_address, MC_TABLE_1, mc_table1_val);

    return SUCCESS;
}

