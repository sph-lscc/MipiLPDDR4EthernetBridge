/**
 * @brief : This API is used to enable the TX and RX functionalities of the
 *          Ethernet IP control option as well as the mac_cfg_options.
 * @param : this_xxv_xethernet - Handle of the xxv_xethernet_instance structure.
 *          options - TX control options and RX control options.
 * @return : Return the success or failure status based on a condition.
 */
int xxv_xethernet_set_mac_options(xxv_xethernet_instance *this_xxv_xethernet, unsigned int options)
{
    if(!this_xxv_xethernet)
        return FAILURE;

    unsigned int mode_val = register_read32(this_xxv_xethernet->config.base_address, MODE);
    unsigned char is_TX_enabled = mode_val & MODE_TX_EN;
    if(is_TX_enabled)
        return FAILURE;
    unsigned char is_RX_enabled = mode_val & MODE_RX_EN;
    if(is_RX_enabled)
        return FAILURE;

    this_xxv_xethernet->mac_cfg_options |= options;

    unsigned int tx_ctl_val = register_read32(this_xxv_xethernet->config.base_address, TX_CTL);
    if(this_xxv_xethernet->mac_cfg_options & MAC_CFG_OPTION_TX_PASS_PREARM) tx_ctl_val |= TX_PASS_PREARM;
    if(this_xxv_xethernet->mac_cfg_options & MAC_CFG_OPTION_TX_SHORT)       tx_ctl_val |= TX_TRANSMIT_SHORT;
    if(this_xxv_xethernet->mac_cfg_options & MAC_CFG_OPTION_TX_IPG_STRETCH) tx_ctl_val |= TX_IPG_STRETCH;
    if(this_xxv_xethernet->mac_cfg_options & MAC_CFG_OPTION_TX_FC_EN)       tx_ctl_val |= TX_FC_EN;
    if(this_xxv_xethernet->mac_cfg_options & MAC_CFG_OPTION_TX_PASS_FCS)    tx_ctl_val |= TX_PASS_FCS;
    register_write32(this_xxv_xethernet->config.base_address, TX_CTL, tx_ctl_val);

    unsigned int rx_ctl_val = register_read32(this_xxv_xethernet->config.base_address, RX_CTL);
    if(this_xxv_xethernet->mac_cfg_options & MAC_CFG_OPTION_RX_PASS_REARM)  rx_ctl_val |= RX_PASS_PREARM;
    if(this_xxv_xethernet->mac_cfg_options & MAC_CFG_OPTION_DROP_MAC_CTRL)  rx_ctl_val |= RX_DROP_MAC_CTRL;
    if(this_xxv_xethernet->mac_cfg_options & MAC_CFG_OPTION_RX_SHORT)       rx_ctl_val |= RX_SHORT;
    if(this_xxv_xethernet->mac_cfg_options & MAC_CFG_OPTION_RX_BC)          rx_ctl_val |= RX_BC;
    if(this_xxv_xethernet->mac_cfg_options & MAC_CFG_OPTION_RX_ALL_MC)      rx_ctl_val |= RX_ALL_MC;
    if(this_xxv_xethernet->mac_cfg_options & MAC_CFG_OPTION_RX_PAUSE_EN)    rx_ctl_val |= RX_PAUSE_EN;
    if(this_xxv_xethernet->mac_cfg_options & MAC_CFG_OPTION_RX_PASS_FCS)    rx_ctl_val |= RX_PASS_FCS;
    if(this_xxv_xethernet->mac_cfg_options & MAC_CFG_OPTION_PRMS)           rx_ctl_val |= RX_PRMS;
    register_write32(this_xxv_xethernet->config.base_address, RX_CTL, rx_ctl_val);

    return SUCCESS;
}

