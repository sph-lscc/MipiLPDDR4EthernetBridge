/**
 * @brief : This API is used to read from value from specific statistic counter register.
 * @param : this_xxv_xethernet - Handle of the xxv_xethernet_instance structure.
 *          reg_offset - Statistic counter register offset.
 *          counter_val - Value of statistic counter.
 * @return : Return the success or failure status based on a condition.
 */
int xxv_xethernet_get_statistic_counter(xxv_xethernet_instance *this_xxv_xethernet, unsigned int reg_offset, unsigned long long *counter_val)
{
    unsigned int counter_val_lo = 0;
    unsigned int counter_val_hi = 0;

    if(!this_xxv_xethernet || !counter_val)
        return FAILURE;

    // check the offset is in valid range
    if(reg_offset < TX_STAT_PKT_LNGTH || reg_offset > (RX_STAT_PKT_9217_16383 + 4))
        return FAILURE;

    counter_val_lo = register_read32(this_xxv_xethernet->config.base_address, reg_offset);

    if(this_xxv_xethernet->config.ip_cfg_options & IP_CFG_OPTION_COUNTER_WIDTH_64_BITS)
    {
        counter_val_hi = register_read32(this_xxv_xethernet->config.base_address, reg_offset + 4);
    }

    *counter_val = (((unsigned long long)counter_val_hi) << 32) | (unsigned long long)counter_val_lo;

    return SUCCESS;
}

/**
 * @brief : This API is used to print the name of the statistic counter register string, along with its corresponding register value.
 * @param : this_xxv_xethernet - Handle of the xxv_xethernet_instance structure.
 *          reg_offset - Statistic counter register offset.
 * @return : Return the success or failure status based on a condition.
 */
int xxv_xethernet_print_statistic_counter(xxv_xethernet_instance *this_xxv_xethernet, unsigned int reg_offset)
{
    if(!this_xxv_xethernet)
        return FAILURE;

    unsigned long long counter_val = 0;
    int error = xxv_xethernet_get_statistic_counter(this_xxv_xethernet, reg_offset, &counter_val);

    printf("statics_counter %s = %16llx\r\n", xxv_xethernet_reg_name_str(reg_offset), counter_val);
    return error;
}
