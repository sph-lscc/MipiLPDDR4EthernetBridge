    unsigned int rx_ctl_val = register_read32(this_xxv_xethernet->config.base_address, RX_CTL);
    if(!(this_xxv_xethernet->mac_cfg_options & MAC_CFG_OPTION_RX_PASS_REARM))  rx_ctl_val &= ~RX_PASS_PREARM;
    if(!(this_xxv_xethernet->mac_cfg_options & MAC_CFG_OPTION_DROP_MAC_CTRL))  rx_ctl_val &= ~RX_DROP_MAC_CTRL;
