/**
 * @brief : This API is used to write data to a specific register.
 * @param : base_address - base address of Ethernet IP.
 *          offset - offset value of a specific register.
 *          val - value to be written into specific register.
 * @return : None.
 */
void register_write32(unsigned int base_address, unsigned int offset, unsigned int val)
{
    volatile unsigned int *const reg = (unsigned int*) (base_address + offset);
    *reg = val;
}

/**
 * @brief : This API is used to read data to a specific register.
 * @param : base_address - base address of Ethernet IP.
 *          offset - offset value of a specific register.
 * @return : None.
 */
