/**
 * @brief : This API is used to activate of the TX MAC and RX MAC functionalities for the Ethernet IP.
 * @param : this_xxv_xethernet - Handle of the xxv_xethernet_instance structure.
 * @return : Return the success or failure status based on a condition.
 */
int xxv_xethernet_start(xxv_xethernet_instance *this_xxv_xethernet)
{
    if(!this_xxv_xethernet)
        return FAILURE;

    unsigned int mode_val = register_read32(this_xxv_xethernet->config.base_address, MODE);
    mode_val |= (MODE_TX_EN | MODE_RX_EN);
    register_write32(this_xxv_xethernet->config.base_address, MODE, mode_val);

    return SUCCESS;
}

